"""The loopback host requires a per-launch token on every API route.

Review item 3. The host served `/api/*` to any local process on the machine, and those routes can change
the ACE runtime directory (which picks the Python that later runs), move the library, copy any folder and
spend Hermes model credits. The token is generated by the launcher, handed to the host in its environment,
returned by `/studio/host`, carried into the framed URL and required on every route except the health
probe.

These fail on the reviewed tree — there was no token at all, so every request was accepted.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest
from fastapi import FastAPI
from fastapi.testclient import TestClient

ROOT = Path(__file__).resolve().parents[1]
TOKEN = "test-token-abc123"


@pytest.fixture()
def client(monkeypatch, tmp_path):
    """The host app with a known token, and one trivial API route to call.

    The data dir is isolated *before* the import: `standalone.app` resolves it at import time, and a test
    that imports the app with the real library in place leaves every later test writing into it.
    """
    monkeypatch.setenv("HEWN_STUDIO_DATA_DIR", str(tmp_path / "studio"))
    monkeypatch.setenv("HEWN_STUDIO_TOKEN", TOKEN)
    from standalone import app as host_app

    app = FastAPI()
    app.middleware("http")(host_app.same_origin)
    from fastapi import APIRouter

    router = APIRouter()

    @router.get("/status")
    def status():
        return {"ok": True}

    @router.get("/projects")
    def projects():
        return {"ok": True, "secret": "library listing"}

    @router.post("/settings")
    def settings():
        return {"ok": True}

    @router.get("/health")
    def health():
        return {"ok": True, "token_gated": True}

    app.include_router(router, prefix="/api")
    # The host middleware requires a loopback Host header as well as the token; the default
    # TestClient host ("testserver") is refused for that reason, not for a missing token.
    return TestClient(app, base_url="http://127.0.0.1:8775")


def test_a_request_without_the_token_is_refused(client):
    response = client.get("/api/projects")
    assert response.status_code == 401
    assert "secret" not in response.text


def test_a_write_without_the_token_is_refused(client):
    assert client.post("/api/settings", json={}).status_code == 401


def test_the_header_carries_the_token(client):
    assert client.get("/api/projects", headers={"X-Studio-Token": TOKEN}).status_code == 200


def test_the_query_string_carries_the_token_for_the_framed_page(client):
    """The framed page is a sandboxed document; a query token is what it can carry on load."""
    assert client.get(f"/api/projects?token={TOKEN}").status_code == 200


def test_a_wrong_token_is_refused(client):
    assert client.get("/api/projects", headers={"X-Studio-Token": "nope"}).status_code == 401


def test_the_health_probe_needs_the_token_like_every_other_api_route(client):
    """Review item 3 asked for the token on every /api/* request, health included.

    The pane's no-cors liveness fetch still works: a 401 is an answer, and an opaque fetch only cares
    that something answered. With the token, health says the host enforces it.
    """
    assert client.get("/api/health").status_code == 401
    response = client.get("/api/health", headers={"X-Studio-Token": TOKEN})
    assert response.status_code == 200
    assert response.json() == {"ok": True, "token_gated": True}
    assert client.get("/api/status").status_code == 401, "status is library data, not liveness"


def test_the_launcher_reads_a_401_from_health_as_a_live_gated_host():
    """A gated host refuses an unauthenticated health probe; that refusal proves it is alive and gated."""
    import http.server
    import threading

    from music_studio import host_launcher

    class Gated(http.server.BaseHTTPRequestHandler):
        def do_GET(self):
            self.send_response(401)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(b'{"detail": "studio token required"}')

        def log_message(self, *args):
            pass

    server = http.server.HTTPServer(("127.0.0.1", 0), Gated)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        assert host_launcher._probe(server.server_address[1]) == {"alive": True, "token_gated": True}
    finally:
        server.shutdown()
        server.server_close()


def test_a_stranger_answering_401_is_not_taken_for_the_studio_host():
    import http.server
    import threading

    from music_studio import host_launcher

    class Stranger(http.server.BaseHTTPRequestHandler):
        def do_GET(self):
            self.send_response(401)
            self.end_headers()
            self.wfile.write(b"login required")

        def log_message(self, *args):
            pass

    server = http.server.HTTPServer(("127.0.0.1", 0), Stranger)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    try:
        assert host_launcher._probe(server.server_address[1]) == {"alive": False, "token_gated": False}
    finally:
        server.shutdown()
        server.server_close()


def test_a_host_without_a_token_refuses_the_api_instead_of_serving_it(monkeypatch, tmp_path):
    """Fail closed. The gate used to disappear with the environment variable, so the documented
    `uvicorn standalone.app:app` invocation served every route to every local process."""
    monkeypatch.setenv("HEWN_STUDIO_DATA_DIR", str(tmp_path / "studio2"))
    monkeypatch.delenv("HEWN_STUDIO_TOKEN", raising=False)
    from fastapi import APIRouter
    from standalone import app as host_app

    app = FastAPI()
    app.middleware("http")(host_app.same_origin)
    router = APIRouter()

    @router.get("/projects")
    def projects():
        return {"ok": True, "secret": "library listing"}

    app.include_router(router, prefix="/api")
    bare = TestClient(app, base_url="http://127.0.0.1:8775")

    refused = bare.get("/api/projects")
    assert refused.status_code == 503, "a host with no token must not serve /api"
    assert "secret" not in refused.text
    assert "HEWN_STUDIO_TOKEN" in refused.json()["detail"]


def test_the_launcher_does_not_reuse_a_host_that_ignores_the_token(monkeypatch, tmp_path):
    """A host started before the update has no gate; handing the pane a token it ignores is not a fix."""
    from music_studio import host_launcher

    monkeypatch.setenv("HEWN_STUDIO_DATA_DIR", str(tmp_path))
    host_launcher._write_state(tmp_path, {"port": 8775, "pid": 111, "token": "old"})
    monkeypatch.setattr(host_launcher, "_probe",
                        lambda port, timeout=1.0: {"alive": True, "token_gated": False})
    monkeypatch.setattr(host_launcher, "_alive", lambda port, timeout=1.0: True)
    monkeypatch.setattr(host_launcher, "_port_free", lambda port: port != 8775)
    monkeypatch.setattr(host_launcher, "_python", lambda: __import__("sys").executable)
    started = []

    class FakeProc:
        pid = 4242
        args = ['fake-studio-host']

        def poll(self):
            return None

        def __enter__(self):
            return self

        def __exit__(self, *exc):
            return False

        def communicate(self, *args, **kwargs):
            return (b'', b'')

        def wait(self, *args, **kwargs):
            return 0

        def terminate(self):
            return None

    def fake_popen(*args, **kwargs):
        started.append(kwargs.get("env") or {})
        return FakeProc()

    monkeypatch.setattr(host_launcher.subprocess, "Popen", fake_popen)

    result = host_launcher.ensure_host()

    assert result["started"] is True, "the ungated host was reused"
    assert result["port"] != 8775, "a new host must not be started on the port the old one holds"
    assert started and started[0]["HEWN_STUDIO_TOKEN"], "the new host must be given a token"


def test_the_launcher_generates_a_random_token_per_launch():
    from music_studio import host_launcher

    first = host_launcher._token_for(ROOT, None, fresh=True)
    second = host_launcher._token_for(ROOT, None, fresh=True)
    reused = host_launcher._token_for(ROOT, {"token": first}, fresh=False)
    assert len(first) >= 32 and first != second, "a per-launch token must not be a constant"
    assert reused == first, "a reused host keeps the token it was started with"


def test_the_pane_passes_the_token_into_the_framed_page():
    pane = (ROOT / "desktop" / "plugin.js").read_text(encoding="utf-8")
    assert "token" in pane and "?token=" in pane, (
        "the framed URL must carry the token, or every request from it is refused"
    )


def test_the_page_sends_the_token_on_every_call():
    page = (ROOT / "standalone" / "static" / "app.js").read_text(encoding="utf-8")
    assert "X-Studio-Token" in page
    assert re.search(r"opts\.headers = withToken", page), (
        "every api() call must carry the header, not just the POSTs"
    )


def test_the_token_is_never_written_into_the_repository():
    """A token is per launch; one in the tree would be a shared secret checked into git."""
    pattern = re.compile(r"[A-Za-z0-9_-]{32,}")
    for path in list(ROOT.rglob("*.json")) + list(ROOT.rglob("*.md")):
        if ".git" in path.parts or "node_modules" in path.parts:
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        if "HEWN_STUDIO_TOKEN" in text and "token" in text:
            continue
        for match in re.findall(r'"token"\s*:\s*"([^"]+)"', text):
            assert not pattern.fullmatch(match), f"{path.relative_to(ROOT)} looks like it stores a token"
